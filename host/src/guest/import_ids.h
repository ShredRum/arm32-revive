// The id of an import name, or ImportId::None (binary search: the table is sorted).
inline ImportId ImportIdForName(const char* name) {
    std::size_t lo = 0, hi = sizeof(kImportIdNames) / sizeof(kImportIdNames[0]);
    while (lo < hi) {
        const std::size_t mid = (lo + hi) / 2;
        const int c = std::strcmp(kImportIdNames[mid], name);
        if (c == 0) {
            return static_cast<ImportId>(mid + 1);
        }
        if (c < 0) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return ImportId::None;
}

